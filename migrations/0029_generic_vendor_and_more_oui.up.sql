-- 2. 27 vendor tambahan (ONT/ONU/router/gateway yang lazim memakai TR-069) beserta
--    OUI-nya dari registry IEEE (MA-L, blok 24-bit), kaidah sama dengan 0022:
--      * sumber: Wireshark `manuf` (turunan IEEE; snapshot 2026-10-17), disilangkan
--        dengan nmap-mac-prefixes (independen): dari 1.128 OUI, 1.063 ada di kedua
--        sumber dan 0 nama registrant tidak cocok; 65 lainnya alokasi baru yang belum
--        ada di nmap. 1 OUI (30075C, Netis) DIKECUALIKAN karena kedua sumber tidak sepakat.
--      * pemetaan per NAMA REGISTRANT PERSIS (bukan substring); tidak ada OUI ganda
--        lintas vendor dan tidak ada yang bentrok dengan seed-0022.
--      * vendor yang punya OUI banyak registrant (mis. Sagemcom, TP-Link) hanya diisi
--        registrant utamanya; OUI lain ditambah operator lewat Catalog Vendor.
--
-- BATASAN yang harus dipahami (jujur):
--   * Ini data awal, BUKAN validasi lapangan: belum ada CPE fisik dari vendor-vendor ini
--     yang diuji. Mapping standar mengandaikan CPE mengikuti TR-098/TR-181 apa adanya;
--     CPE dengan struktur nonstandar (mis. index WLANConfiguration berbeda, parameter
--     optik vendor-extension) tetap butuh mapping vendor/model sendiri via Catalog Vendor
--     (VENDOR_ONBOARDING.md). Mapping tak cocok -> task gagal dengan pesan jelas, bukan
--     merusak konfigurasi: raw TR-069 path tetap bisa dipakai.
--   * OUI di DeviceId TR-069 adalah OUI produsen dan BELUM TENTU sama dengan OUI MAC
--     unit; cocokkan dengan Inform nyata pertama.
--   * Idempoten: vendor yang sudah ada diaktifkan kembali (is_deleted=0), OUI yang sudah
--     ada tidak ditimpa (pilihan manual menang).
--   * Rollback (.down): mapping GENERIC & OUI ber-marker 'seed-0029' dihapus FISIK
--     (pembatalan seed, bukan data master operator); vendor di-SOFT-DELETE (bisa
--     dirujuk device yang sudah terlanjur terhubung).
