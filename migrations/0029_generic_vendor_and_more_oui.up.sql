  ON DUPLICATE KEY UPDATE is_deleted = 0, deleted_at = NULL, deleted_by = NULL;

INSERT INTO vendor_parameter_mappings
    (vendor_id, data_model_version_id, device_model_id, software_version_pattern, logical_key, tr069_path, parameter_type_id, value_scale, description)
SELECT g.id, m.data_model_version_id, NULL, NULL, m.logical_key, m.tr069_path, m.parameter_type_id, m.value_scale, m.description
FROM vendor_parameter_mappings m
JOIN ref_vendors z ON z.id = m.vendor_id AND z.code = 'ZTE' AND z.is_deleted = 0
JOIN ref_vendors g ON g.code = 'GENERIC' AND g.is_deleted = 0
WHERE m.device_model_id IS NULL AND m.software_version_pattern IS NULL AND m.is_deleted = 0
  AND NOT EXISTS (
      SELECT 1 FROM vendor_parameter_mappings x
      WHERE x.vendor_id = g.id AND x.data_model_version_id = m.data_model_version_id
        AND x.logical_key = m.logical_key AND x.device_model_id IS NULL
        AND x.software_version_pattern IS NULL AND x.is_deleted = 0
  );

